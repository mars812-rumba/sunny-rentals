for (const page of commercialPages) {
  for (const locale of ["ru", "en"] as const) {
    const policy = policyCopy(locale);
    page[locale].sections.push({
      title: locale === "ru" ? "Доставка и условия" : "Delivery and terms",
      paragraphs: [policy.delivery, page[locale].vehicleCategories?.includes("bikes")
        && page[locale].vehicleCategories?.length === 1 ? policy.scooterCover
        : page[locale].requiresChildSeat ? policy.childSeat : policy.insurance],
    });
    if (page[locale].slug === "short-term-car-rental-phuket" || page[locale].slug === "long-term-car-rental-phuket") {
      page[locale].sections.push({
        title: locale === "ru" ? "Предоплата и возврат автомобиля" : "Car booking advance and return",
        paragraphs: [policy.carBooking, policy.depositReturn],
      });
    }
  }
}
